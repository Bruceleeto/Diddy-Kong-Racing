#!/usr/bin/env python3
"""Make the VMU save file's icon from the game's own art.

usage: build_vmu_icon.py diddy_icon.png out.h

The icon is Diddy's race-position portrait (a 40x40 HUD texture extracted from
the ROM), its framed border cut away to the 32x32 inside, as the VMU's file
menu shows it: 16 colours in ARGB4444, two pixels a byte, the left one in the
high nibble. Nothing from the ROM is in the repository; this runs at build time.
"""
import struct
import sys
import zlib

import numpy as np

SIZE = 32
CROP = 4  # the portrait's frame, on every side
COLOURS = 16


def read_png_rgba(path):
    """An 8-bit RGBA or RGB, non-interlaced PNG as a (height, width, 4) array."""
    data = open(path, "rb").read()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        sys.exit(f"{path}: not a PNG")
    pos, idat, width = 8, b"", 0
    while pos < len(data):
        length, kind = struct.unpack(">I4s", data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + length]
        if kind == b"IHDR":
            width, height, depth, colour, _, _, interlace = struct.unpack(">IIBBBBB", body)
            if depth != 8 or colour not in (2, 6) or interlace:
                sys.exit(f"{path}: needs 8-bit RGB or RGBA, not interlaced")
            channels = 4 if colour == 6 else 3
        elif kind == b"IDAT":
            idat += body
        pos += 12 + length
    raw = zlib.decompress(idat)
    stride = width * channels
    rows, prev = [], bytearray(stride)
    for y in range(height):
        kind, line = raw[y * (stride + 1)], bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for i in range(stride):
            left = line[i - channels] if i >= channels else 0
            up = prev[i]
            corner = prev[i - channels] if i >= channels else 0
            if kind == 1:
                line[i] = (line[i] + left) & 0xFF
            elif kind == 2:
                line[i] = (line[i] + up) & 0xFF
            elif kind == 3:
                line[i] = (line[i] + (left + up) // 2) & 0xFF
            elif kind == 4:
                p = left + up - corner
                pa, pb, pc = abs(p - left), abs(p - up), abs(p - corner)
                line[i] = (line[i] + (left if pa <= pb and pa <= pc else up if pb <= pc else corner)) & 0xFF
        rows.append(bytes(line))
        prev = line
    image = np.frombuffer(b"".join(rows), dtype=np.uint8).reshape(height, width, channels)
    if channels == 3:
        image = np.concatenate([image, np.full((height, width, 1), 255, np.uint8)], axis=2)
    return image


def median_cut(pixels, count):
    """count representative colours of pixels (N, 3), by splitting the widest box."""
    boxes = [pixels]
    while len(boxes) < count:
        index = max(range(len(boxes)), key=lambda i: np.ptp(boxes[i], axis=0).max() if len(boxes[i]) > 1 else -1)
        box = boxes[index]
        if len(box) < 2:
            break
        channel = int(np.argmax(np.ptp(box, axis=0)))
        box = box[np.argsort(box[:, channel], kind="stable")]
        half = len(box) // 2
        boxes[index:index + 1] = [box[:half], box[half:]]
    return np.array([np.round(box.mean(axis=0)) for box in boxes], dtype=np.int32)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    image = read_png_rgba(sys.argv[1])
    if image.shape[0] < SIZE + 2 * CROP or image.shape[1] < SIZE + 2 * CROP:
        sys.exit(f"{sys.argv[1]}: smaller than {SIZE + 2 * CROP} pixels")
    rgb = image[CROP:CROP + SIZE, CROP:CROP + SIZE, :3].reshape(-1, 3).astype(np.int32)
    # The VMU shows 4 bits a channel. Split the distinct colours, each counted
    # once, so the big blue background cannot take several palette entries from
    # the cap and the face; then refine by how many pixels each colour covers.
    rgb = (rgb >> 4) * 17
    colours, counts = np.unique(rgb, axis=0, return_counts=True)
    palette = median_cut(colours, COLOURS).astype(np.float64)
    for _ in range(20):
        nearest = np.argmin(((colours[:, None, :] - palette[None, :, :]) ** 2).sum(axis=2), axis=1)
        for k in range(len(palette)):
            members = nearest == k
            if members.any():
                palette[k] = (colours[members] * counts[members, None]).sum(axis=0) / counts[members].sum()
    palette = np.clip(np.round(palette / 17) * 17, 0, 255).astype(np.int32)
    # Each pixel to its nearest palette colour, no dithering: the portrait stays crisp.
    index = np.argmin(((rgb[:, None, :] - palette[None, :, :]) ** 2).sum(axis=2), axis=1)
    argb4444 = [0xF000 | ((r >> 4) << 8) | ((g >> 4) << 4) | (b >> 4) for r, g, b in palette.tolist()]
    argb4444 += [0xF000] * (COLOURS - len(argb4444))
    packed = [(int(index[i]) << 4) | int(index[i + 1]) for i in range(0, SIZE * SIZE, 2)]

    lines = ["// Generated by dreamcast/build_vmu_icon.py from the ROM's Diddy portrait.",
             "static const uint16_t sDkrVmuIconPal[16] = {",
             "    " + ", ".join(f"0x{c:04X}" for c in argb4444), "};",
             "static const uint8_t sDkrVmuIconData[512] = {"]
    for i in range(0, len(packed), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in packed[i:i + 16]) + ",")
    lines.append("};")
    open(sys.argv[2], "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
